#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Install a user Application Menu entry that launches this checkout via run.sh
# (absolute path). No root required. For the packaged .deb, the system
# .desktop is installed under /usr/share/applications/ instead.
#
# Usage:
#   ./scripts/install-desktop.sh          # install / refresh
#   ./scripts/install-desktop.sh --remove # uninstall user entry + icon
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RUN_SH="${ROOT}/run.sh"
DESKTOP_SRC="${ROOT}/packaging/mxmaster-cfg.desktop"
ICON_SRC="${ROOT}/packaging/icons/mxmaster-cfg.svg"

APPS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
ICONS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor/scalable/apps"
DESKTOP_DST="${APPS_DIR}/mxmaster-cfg.desktop"
ICON_DST="${ICONS_DIR}/mxmaster-cfg.svg"

if [[ "${1:-}" == "--remove" ]]; then
  rm -f "$DESKTOP_DST" "$ICON_DST"
  if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$APPS_DIR" 2>/dev/null || true
  fi
  if command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -f \
      "${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor" 2>/dev/null || true
  fi
  echo "Removed user launcher: $DESKTOP_DST"
  exit 0
fi

if [[ ! -x "$RUN_SH" ]]; then
  echo "error: run.sh missing or not executable: $RUN_SH" >&2
  exit 1
fi
if [[ ! -f "$DESKTOP_SRC" ]]; then
  echo "error: desktop template missing: $DESKTOP_SRC" >&2
  exit 1
fi

install -d "$APPS_DIR" "$ICONS_DIR"
if [[ -f "$ICON_SRC" ]]; then
  install -m 0644 "$ICON_SRC" "$ICON_DST"
fi

# Rewrite Exec/Path/Icon for this checkout; keep Name/Comment from template.
{
  echo "# Generated by scripts/install-desktop.sh — do not edit by hand"
  echo "# Source tree: $ROOT"
  # Drop Exec/TryExec/Path/Icon lines; we set absolute ones below.
  grep -vE '^(Exec|TryExec|Path|Icon)=' "$DESKTOP_SRC" || true
  echo "Exec=${RUN_SH}"
  echo "Path=${ROOT}"
  echo "Icon=mxmaster-cfg"
  echo "TryExec=${RUN_SH}"
} >"$DESKTOP_DST"
chmod 0644 "$DESKTOP_DST"

if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$APPS_DIR" 2>/dev/null || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
  gtk-update-icon-cache -f \
    "${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor" 2>/dev/null || true
fi
if command -v kbuildsycoca6 >/dev/null 2>&1; then
  kbuildsycoca6 --noincremental 2>/dev/null || true
elif command -v kbuildsycoca5 >/dev/null 2>&1; then
  kbuildsycoca5 --noincremental 2>/dev/null || true
fi

echo "Installed Application Menu entry:"
echo "  $DESKTOP_DST"
echo "  Exec=$RUN_SH"
echo "  Icon=$ICON_DST"
echo "Look for «MX Master Config» in the menu (may need a moment to refresh)."
